export type ThemeTokens = Record<string, string>;

export interface ThemeSource {
  allAppearance: string[];
  allColor: string[];
  base: Record<string, ThemeTokens>;
  colors: Record<string, Record<string, ThemeTokens>>;
}

export interface ResolvedTheme {
  color: string;
  appearance: string;
  tokens: ThemeTokens;
}

const generatedNotice = "Generated by scripts/themes/generate.ts from assets/themes/themes.json; edit the JSON and run make generate-themes.";
const iosTokenPrefix = "ios";
// The iPhone and Android apps read the same ios* tokens: tint, text on it, the grouped background, secondary labels, warnings.
const allPhoneToken = ["iosTint", "iosOnTint", "iosGroupedBackground", "iosSecondaryLabel", "iosWarning"];

export function resolveAllTheme(source: ThemeSource): ResolvedTheme[] {
  return source.allColor.flatMap((color) =>
    source.allAppearance.map((appearance) => ({
      color,
      appearance,
      tokens: { ...source.base[appearance], ...source.colors[color][appearance] },
    })),
  );
}

export function convertToKebabCase(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function renderDeclarationBlock(allSelector: string[], theme: ResolvedTheme, indent: string): string {
  const allDeclaration = [`color-scheme: ${theme.appearance};`];
  for (const [name, value] of Object.entries(theme.tokens)) {
    if (!name.startsWith(iosTokenPrefix)) {
      allDeclaration.push(`--color-${convertToKebabCase(name)}: ${value};`);
    }
  }
  return `${indent}${allSelector.join(`,\n${indent}`)} {\n${allDeclaration.map((declaration) => `${indent}  ${declaration}`).join("\n")}\n${indent}}\n`;
}

function createSelector(color: string, appearance: string): string {
  return `[data-color="${color}"][data-appearance="${appearance}"]`;
}

// System follows prefers-color-scheme; a page without attributes gets Neutral, following the system too.
export function renderThemeCSS(source: ThemeSource): string {
  const allTheme = resolveAllTheme(source);
  let css = `/* ${generatedNotice} */\n`;
  for (const theme of allTheme) {
    const allSelector = [createSelector(theme.color, theme.appearance)];
    if (theme.color === source.allColor[0] && theme.appearance === "dark") {
      allSelector.unshift(":root");
    }
    css += "\n" + renderDeclarationBlock(allSelector, theme, "");
  }
  for (const appearance of source.allAppearance) {
    css += `\n@media (prefers-color-scheme: ${appearance}) {\n`;
    const allBlock = allTheme
      .filter((theme) => theme.appearance === appearance)
      .map((theme) => {
        const allSelector = [createSelector(theme.color, "system")];
        if (theme.color === source.allColor[0]) {
          allSelector.unshift(":root:not([data-appearance])");
        }
        return renderDeclarationBlock(allSelector, theme, "  ");
      });
    css += allBlock.join("\n") + "}\n";
  }
  return css;
}

function convertToRGB(value: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(value)) {
    throw new Error(`phone colours must be #rrggbb, got ${value}`);
  }
  return value.slice(1).toUpperCase();
}

function convertToPaletteName(name: string): string {
  const withoutPrefix = name.slice(iosTokenPrefix.length);
  return withoutPrefix[0].toLowerCase() + withoutPrefix.slice(1);
}

function findPhoneTokens(source: ThemeSource, color: string): { light: ThemeTokens; dark: ThemeTokens } {
  const allTheme = resolveAllTheme(source);
  const findTokens = (appearance: string) => allTheme.find((theme) => theme.color === color && theme.appearance === appearance)!.tokens;
  return { light: findTokens("light"), dark: findTokens("dark") };
}

// Cells keep the system colours; iosCellBackground is in the JSON only for the contrast check.
export function renderThemeSwift(source: ThemeSource): string {
  let swift = `// ${generatedNotice}\n\nextension ThemePalette {\n`;
  for (const color of source.allColor) {
    const { light, dark } = findPhoneTokens(source, color);
    const allArgument = allPhoneToken.map(
      (name) => `        ${convertToPaletteName(name)}: ThemeColor(light: 0x${convertToRGB(light[name])}, dark: 0x${convertToRGB(dark[name])})`,
    );
    swift += `    static let ${color} = ThemePalette(\n${allArgument.join(",\n")}\n    )\n\n`;
  }
  swift += `    static func find(color: ThemeColorName) -> ThemePalette {\n        switch color {\n`;
  for (const color of source.allColor) {
    swift += `        case .${color}: ${color}\n`;
  }
  swift += `        }\n    }\n}\n`;
  return swift;
}

// Opaque ARGB values, so the model module stays free of Android and Compose.
export function renderThemeKotlin(source: ThemeSource): string {
  let kotlin = `// ${generatedNotice}\n\npackage com.tryhisar.hisar.model.theme\n\nimport com.tryhisar.hisar.model.ThemeColorName\n\nobject ThemePalettes {\n`;
  for (const color of source.allColor) {
    const { light, dark } = findPhoneTokens(source, color);
    const allArgument = allPhoneToken.map(
      (name) => `        ${convertToPaletteName(name)} = ThemeColor(light = 0xFF${convertToRGB(light[name])}, dark = 0xFF${convertToRGB(dark[name])}),`,
    );
    allArgument.push(`        destructiveText = ThemeColor(light = 0xFF${convertToRGB(light.dangerText)}, dark = 0xFF${convertToRGB(dark.dangerText)}),`);
    kotlin += `    val ${color} = ThemePalette(\n${allArgument.join("\n")}\n    )\n\n`;
  }
  kotlin += `    fun find(color: ThemeColorName): ThemePalette = when (color) {\n`;
  for (const color of source.allColor) {
    kotlin += `        ThemeColorName.${color.toUpperCase()} -> ${color}\n`;
  }
  kotlin += `    }\n}\n`;
  return kotlin;
}

function convertToLinear(channel: number): number {
  const value = channel / 255;
  return value <= 0.04045 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
}

export function computeRelativeLuminance(hexadecimal: string): number {
  const value = parseInt(hexadecimal.slice(1), 16);
  return 0.2126 * convertToLinear((value >> 16) & 255) + 0.7152 * convertToLinear((value >> 8) & 255) + 0.0722 * convertToLinear(value & 255);
}

export function computeContrastRatio(foreground: string, background: string): number {
  const foregroundLuminance = computeRelativeLuminance(foreground);
  const backgroundLuminance = computeRelativeLuminance(background);
  return (Math.max(foregroundLuminance, backgroundLuminance) + 0.05) / (Math.min(foregroundLuminance, backgroundLuminance) + 0.05);
}
