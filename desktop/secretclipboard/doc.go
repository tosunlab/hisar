// Package secretclipboard owns the Linux clipboard for Hisar's copies on a connection of its own, so that it can offer
// x-kde-passwordManagerHint "secret" beside the text: GTK 4 lists such a type but never sends its value (it refuses
// MIME types without a "/"), and KDE's Klipper and CopyQ keep a copy out of their history only when the value reads
// "secret". On X11 it owns CLIPBOARD through Xlib; on Wayland it uses the data-control protocol (ext-data-control-v1,
// else wlr-data-control-unstable-v1), which GNOME's compositor does not have. A worker thread per connection answers
// paste requests.
//
// The protocol code is generated by wayland-scanner 1.23 from ext-data-control-v1.xml (wayland-protocols, staging) and
// wlr-data-control-unstable-v1.xml (wlr-protocols):
//
//	wayland-scanner client-header <protocol>.xml <protocol>-client-protocol.h
//	wayland-scanner private-code <protocol>.xml <protocol, with "_" for "-">_linux.c
